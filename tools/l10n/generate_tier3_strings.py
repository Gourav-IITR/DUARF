lang_map = {
    "gu": gu_strings,
    "kn": kn_strings,
    "ml": ml_strings,
    "pa": pa_strings
}

# Read English file lines to keep exact layout and comments
with open("app/src/main/res/values/strings.xml", "r", encoding="utf-8") as f:
    template_lines = f.readlines()

import re

for lang_code, trans_dict in lang_map.items():
    out_dir = f"app/src/main/res/values-{lang_code}"
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "strings.xml")
    
    out_lines = []
    for line in template_lines:
        match = re.search(r'<string name="([^"]+)">([^<]+)</string>', line)
        if match:
            key = match.group(1)
            val = trans_dict.get(key, match.group(2))
            # replace inside line
            replaced = re.sub(r'>.*<', f'>{val}<', line)
            out_lines.append(replaced)
        else:
            out_lines.append(line)
            
    with open(out_file, "w", encoding="utf-8") as f:
        f.writelines(out_lines)
    print(f"Generated {out_file} with {len(trans_dict)} keys.")
